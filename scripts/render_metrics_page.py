"""Render the public metrics page from eval history.

Reads ``evals/history/runs.jsonl`` and writes a single self-contained HTML
file to ``docs/metrics/index.html`` — no external CDN, no JS, no CSS
framework. Regenerated by ``make metrics-page`` locally and by the
nightly workflow in CI.

Design language matches the demo UI (system font stack, calm blue
accent, dark mode via ``prefers-color-scheme``). See ADR-0010 §Public
metrics page for the motivation.

Sections rendered:

- Headline card: latest run, gate pass/fail, current production config.
- Ablation table with inline sparklines per metric column.
- Quality-vs-cost scatter: one dot per (strategy, corrective) combo.
- "Impact of corrective RAG" panel — delta per strategy that has both
  corrective on and corrective off runs (references ADR-0007).

The file-level E501 waiver is intentional: HTML/SVG templates
unavoidably have wide f-strings, and forcing breaks makes them less
readable, not more.
"""

